/**
 * Builds the postcode -> coordinates table from swisstopo's
 * "Amtliches Ortschaftenverzeichnis" WGS84 CSV
 * (data.geo.admin.ch, ch.swisstopo-vd.ortschaftenverzeichnis_plz, open licence).
 *
 * Header: Ortschaftsname;PLZ4;Zusatzziffer;ZIP_ID;Gemeindename;BFS-Nr;
 *         Kantonskürzel;Adressenanteil;E;N;Sprache;Validity
 * In the WGS84 file E is the longitude and N the latitude. The file starts
 * with a byte order mark.
 */
export type CoordTable = Record<string, [number, number]>;

export const MIN_ROWS = 4000;

export function parsePostcodeCsv(csv: string): { rows: number; table: CoordTable } {
  const lines = csv.replace(/^﻿/, "").split(/\r?\n/).filter((l) => l.trim() !== "");
  const header = lines[0].split(";");
  const col = (name: string) => {
    const i = header.indexOf(name);
    if (i < 0) throw new Error(`swisstopo CSV: column "${name}" not found in header ${header.join(";")}`);
    return i;
  };
  const iPlz = col("PLZ4");
  const iZusatz = col("Zusatzziffer");
  const iE = col("E");
  const iN = col("N");

  const byPlz = new Map<string, { zusatz: string; lat: number; lng: number }[]>();
  for (const line of lines.slice(1)) {
    const cells = line.split(";");
    const plz = cells[iPlz]?.trim();
    const lng = Number(cells[iE]);
    const lat = Number(cells[iN]);
    if (!/^\d{4}$/.test(plz ?? "") || !Number.isFinite(lat) || !Number.isFinite(lng)) continue;
    const list = byPlz.get(plz) ?? [];
    list.push({ zusatz: (cells[iZusatz] ?? "00").trim().padStart(2, "0"), lat, lng });
    byPlz.set(plz, list);
  }

  const r5 = (n: number) => Number(n.toFixed(5));
  const table: CoordTable = {};
  let rows = 0;
  for (const [plz, list] of [...byPlz.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    rows += list.length;
    const mean = (k: "lat" | "lng") => list.reduce((s, r) => s + r[k], 0) / list.length;
    table[plz] = [r5(mean("lat")), r5(mean("lng"))];
    // Per-Zusatzziffer keys only where a postcode really has several (e.g. 1000 Lausanne 25/26/27).
    if (new Set(list.map((r) => r.zusatz)).size > 1) {
      for (const r of list) table[`${plz}${r.zusatz}`] = [r5(r.lat), r5(r.lng)];
    }
  }
  return { rows, table };
}

/** Source of src/shared/swiss-postcode-coordinates.ts. */
export function renderDatasetModule(table: CoordTable, generatedOn: string): string {
  const body = Object.entries(table)
    .map(([k, [lat, lng]]) => `  "${k}": [${lat}, ${lng}],`)
    .join("\n");
  return `// GENERATED by \`npm run companies -- geo-dataset\` on ${generatedOn}. Do not edit.
// Source: swisstopo, Amtliches Ortschaftenverzeichnis (WGS84), opendata.swiss, open use.
// Key "<PLZ>" is the mean of that postcode's rows; "<PLZ><Zusatzziffer>" exists only
// where a postcode has several additional digits. Value is [lat, lng].
export const POSTCODE_COORDS: Readonly<Record<string, readonly [number, number]>> = {
${body}
};
`;
}
